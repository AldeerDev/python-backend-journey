def sumar(a: int, b: int) -> int:
    """
    Suma los numeros enteros a y b.

    Args:
        a: número entero.
        b: número entero.

    Returns:
        Retorna el resultado de la suma de a y b.
    """
    return a + b

def restar(a: int, b: int) -> int:
    """
    Realiza una resta entre a y b, devolviendo el resultado.

    Args:
        a: número entero.
        b: número entero.

    Returns:
        Retorna el resultado de restar a entre b.
    """
    return a - b 